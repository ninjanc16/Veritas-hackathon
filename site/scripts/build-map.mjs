// Builds src/data/map.json: the Rio Grande, the three states it crosses and the
// farm counties along it, already projected to flat coordinates for the page.
//
// Sources: Natural Earth river centrelines (scripts/cache/rivers.geojson) and
// U.S. Census county shapes via the us-atlas package.
// County rule, the same one the research uses: a county is "along the river"
// when its centre is within 50 km of the river's main line.
//
// Run:  node scripts/build-map.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoCentroid, geoDistance, geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const BUFFER_KM = 50
const EARTH_KM = 6371
const STATES = { '08': 'Colorado', 35: 'New Mexico', 48: 'Texas' }
const SIZE = 1000

// 1. The river: chain every Rio Grande piece (river and reservoir centrelines)
//    into one line from the headwaters to the Gulf.
const rivers = JSON.parse(readFileSync(new URL('./cache/rivers.geojson', import.meta.url)))
const pieces = rivers.features
  .filter((f) => f.properties.name === 'Rio Grande')
  .flatMap((f) => (f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates))
  .filter((l) => l.every(([lon, lat]) => lon < -96 && lon > -109 && lat > 25 && lat < 39))
const gap = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1])
pieces.sort((a, b) => Math.max(b[0][1], b.at(-1)[1]) - Math.max(a[0][1], a.at(-1)[1]))
let line = pieces.shift()
if (line[0][1] < line.at(-1)[1]) line = line.toReversed()
while (pieces.length) {
  const end = line.at(-1)
  let best = 0
  let bestD = Infinity
  let flip = false
  pieces.forEach((p, i) => {
    const d0 = gap(end, p[0])
    const d1 = gap(end, p.at(-1))
    if (Math.min(d0, d1) < bestD) [best, bestD, flip] = [i, Math.min(d0, d1), d1 < d0]
  })
  const [p] = pieces.splice(best, 1)
  line = line.concat(flip ? p.toReversed() : p)
}

// Densify so distances to the line are measured every few km.
const dense = []
for (let i = 1; i < line.length; i++) {
  const [a, b] = [line[i - 1], line[i]]
  const n = Math.max(1, Math.ceil((geoDistance(a, b) * EARTH_KM) / 4))
  for (let k = 0; k < n; k++) dense.push([a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n])
}
dense.push(line.at(-1))
const cum = [0]
for (let i = 1; i < dense.length; i++) cum.push(cum[i - 1] + geoDistance(dense[i - 1], dense[i]) * EARTH_KM)
const riverKm = cum.at(-1)

// 2. States and counties.
const topo = require('us-atlas/counties-10m.json')
const states = feature(topo, topo.objects.states).features.filter((f) => STATES[f.id])
const counties = feature(topo, topo.objects.counties)
  .features.filter((f) => STATES[f.id.slice(0, 2)])
  .map((f) => {
    const c = geoCentroid(f)
    let km = Infinity
    let at = 0
    for (let i = 0; i < dense.length; i += 2) {
      const d = geoDistance(c, dense[i]) * EARTH_KM
      if (d < km) [km, at] = [d, i]
    }
    return { f, c, km, frac: cum[at] / riverKm }
  })
  .filter((c) => c.km <= BUFFER_KM)
  .sort((a, b) => a.frac - b.frac)

// 3. Project. One Mercator fit to the three states, drawn in a 1000-wide box.
const projection = geoMercator().fitWidth(SIZE, { type: 'FeatureCollection', features: states })
const path = geoPath(projection).digits(1)
const [, [, height]] = path.bounds({ type: 'FeatureCollection', features: states })
const pt = (c) => projection(c).map((v) => Math.round(v * 10) / 10)

const out = {
  note: 'Generated by scripts/build-map.mjs. Do not edit by hand.',
  width: SIZE,
  height: Math.ceil(height),
  riverKm: Math.round(riverKm),
  river: 'M' + dense.filter((_, i) => i % 2 === 0 || i === dense.length - 1).map((c) => pt(c).join(',')).join('L'),
  states: states.map((s) => ({ name: STATES[s.id], d: path(s), at: pt(geoCentroid(s)) })),
  counties: counties.map(({ f, c, frac }) => ({
    id: f.id,
    name: f.properties.name,
    state: STATES[f.id.slice(0, 2)],
    d: path(f),
    at: pt(c),
    frac: Math.round(frac * 1000) / 1000,
  })),
  places: [
    ['Creede', -106.926, 37.849],
    ['Alamosa', -105.87, 37.469],
    ['Taos', -105.573, 36.407],
    ['Santa Fe', -105.938, 35.687],
    ['Albuquerque', -106.65, 35.084],
    ['Socorro', -106.891, 34.058],
    ['Las Cruces', -106.778, 32.319],
    ['El Paso · Ciudad Juárez', -106.485, 31.762],
    ['Presidio · Ojinaga', -104.372, 29.561],
    ['Del Rio', -100.896, 29.363],
    ['Laredo · Nuevo Laredo', -99.507, 27.506],
    ['McAllen', -98.23, 26.204],
    ['Brownsville · Matamoros', -97.497, 25.902],
  ].map(([name, lon, lat]) => {
    let km = Infinity
    let at = 0
    dense.forEach((d, i) => {
      const v = geoDistance([lon, lat], d)
      if (v < km) [km, at] = [v, i]
    })
    return { name, at: pt([lon, lat]), frac: Math.round((cum[at] / riverKm) * 1000) / 1000 }
  }),
  // Enough to turn a point on the map back into latitude and longitude.
  proj: { k: projection.scale(), tx: projection.translate()[0], ty: projection.translate()[1] },
}
// 4. Context for the journey: tributaries, Mexico, reservoirs, the dry reach
//    and the stations where the story stops.
const fracOf = ([lon, lat]) => {
  let km = Infinity
  let at = 0
  dense.forEach((d, i) => {
    const v = geoDistance([lon, lat], d)
    if (v < km) [km, at] = [v, i]
  })
  return { frac: Math.round((cum[at] / riverKm) * 1000) / 1000, km: km * EARTH_KM, at }
}
const linePath = (coords) => 'M' + coords.map((c) => pt(c).join(',')).join('L')

out.tributaries = []
for (const name of ['Pecos', 'Conchos', 'San Juan']) {
  const parts = rivers.features
    .filter((f) => f.properties.name === name)
    .flatMap((f) => (f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates))
  // Keep it only if it actually meets the Rio Grande, and note where.
  let meet = null
  for (const part of parts) for (const end of [part[0], part.at(-1)]) {
    const m = fracOf(end)
    if (m.km < 25 && (!meet || m.km < meet.km)) meet = m
  }
  if (!meet) continue
  out.tributaries.push({ name, frac: meet.frac, d: parts.map(linePath).join('') })
}

const world = require('world-atlas/countries-50m.json')
const mexico = feature(world, world.objects.countries).features.find((f) => f.id === '484')
out.mexico = path(mexico)

const sub = (a, b) => linePath(dense.slice(fracOf(a).at, fracOf(b).at + 1))
// Fort Quitman to Presidio: the "Forgotten Reach".
out.dryReach = { d: sub([-105.6, 31.06], [-104.37, 29.56]), from: fracOf([-105.6, 31.06]).frac, to: fracOf([-104.37, 29.56]).frac }

out.reservoirs = [
  ['Elephant Butte', -107.19, 33.25],
  ['Amistad', -101.06, 29.46],
  ['Falcon', -99.16, 26.56],
].map(([name, lon, lat]) => ({ name, at: pt([lon, lat]), frac: fracOf([lon, lat]).frac }))

// Where the story stops. `id` matches a chapter in src/content.js.
out.stations = [
  ['source', line[0][0], line[0][1]],
  ['valley', -105.87, 37.47], // Alamosa, San Luis Valley
  ['middle', -106.65, 35.08], // Albuquerque
  ['butte', -107.19, 33.25], // Elephant Butte
  ['pass', -106.49, 31.76], // El Paso and Ciudad Juarez
  ['reach', -104.95, 30.5], // between Fort Quitman and Presidio
  ['conchos', -104.37, 29.56], // Presidio, where the Conchos joins
  ['lower', -98.23, 26.1], // Lower Rio Grande Valley
  ['gulf', line.at(-1)[0], line.at(-1)[1]],
].map(([id, lon, lat]) => ({ id, at: pt([lon, lat]), frac: id === 'gulf' ? 1 : fracOf([lon, lat]).frac }))
out.labels = [
  ['MEXICO', -103.2, 27.4],
  ['GULF OF MEXICO', -95.2, 26.6],
].map(([name, lon, lat]) => ({ name, at: pt([lon, lat]) }))

writeFileSync(new URL('../src/data/map.json', import.meta.url), JSON.stringify(out))
const by = {}
for (const c of out.counties) by[c.state] = (by[c.state] || 0) + 1
console.log(`river ${out.riverKm} km, ${out.counties.length} counties`, by, `box ${out.width}x${out.height}`)
console.log('tributaries', out.tributaries.map((t) => t.name + '@' + t.frac), 'stations', out.stations.map((s) => s.id + '@' + s.frac).join(' '), 'dry', out.dryReach.from, out.dryReach.to)
